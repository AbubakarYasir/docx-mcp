# ── ornaments (built by islamic_art) ──────────────────────────────────


def ornament_svg(
    kind: str,
    *,
    color: str = "520912",
    accent: str | None = None,
    aspect: float | None = None,
    points: int = 12,
    weight: float = 1.0,
    style: str | None = None,
    number: str | None = None,
    border: str | None = None,
    font: str = "Amiri",
) -> str:
    """SVG markup for a generated ornament.

    Args:
        kind: One of ORNAMENTS.
        color: Main colour (lines, or the body of a cartouche / ring).
        accent: Secondary colour (fills; default a light tint of color).
        aspect: Width / height for dividers, bands, cartouches and frames.
        points: Fold of a rosette (8, 10, 12, 16) or petals of a shamsa.
        weight: Line weight multiplier (swash divider).
        style: band / frame: rings, chain, hex-chain, khatam, 8, 6.
        number: Text in the centre of a star medallion (e.g. "١٢").
        border: Edge colour of a cartouche (default gold #b79a5b).
        font: Font of the medallion number.
    """
    if kind not in ORNAMENTS:
        raise ValueError(f"kind must be one of {ORNAMENTS}")
    c = "#" + (color_hex(color) or "520912")
    acc = ("#" + color_hex(accent)) if accent else None
    if kind == "star8":
        return ia.star_medallion(c, acc, number=number, font=font)
    if kind == "rosette":
        return ia.rosette(c, acc, fold=points if points in (8, 10, 12, 16) else 12)
    if kind == "shamsa":
        return ia.shamsa(c, acc or ia.tint(c, 0.82), petals=points if points >= 16 else 24)
    if kind == "ring":
        return ia.ring(c)
    if kind == "divider":
        return ia.swash_divider(c, aspect=aspect or 12.0, weight=weight)
    if kind == "divider-dots":
        return ia.dots_divider(c, aspect=aspect or 10.0)
    if kind == "corner":
        return ia.corner(c, acc)
    if kind == "band":
        return ia.band(c, acc, aspect=aspect or 12.0, kind=style or "rings")
    if kind == "frame":
        return ia.frame(c, acc, aspect=aspect or (210 / 297), kind=style or "rings")
    shape = kind.split("-", 1)[1]
    edge = "#" + (color_hex(border) or "b79a5b") if border else "#b79a5b"
    return ia.cartouche(
        shape,
        color=c,
        border=edge,
        aspect=aspect or 3.2,
        knob=shape == "lobed",
        finials=shape == "banner",
    )


def _tint(hex_color: str, amount: float) -> str:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    r, g, b = (round(v + (255 - v) * amount) for v in (r, g, b))
    return f"#{r:02x}{g:02x}{b:02x}"


def _svg_size(svg: str) -> tuple[float, float]:
    root = etree.fromstring(svg.encode("utf-8"))
    vb = root.get("viewBox")
    if vb:
        parts = [float(v) for v in re.split(r"[ ,]+", vb.strip())]
        if len(parts) == 4 and parts[2] > 0 and parts[3] > 0:
            return parts[2], parts[3]

    def num(v: str | None) -> float:
        m = re.match(r"[\d.]+", v or "")
        return float(m.group(0)) if m else 0.0

    w, h = num(root.get("width")), num(root.get("height"))
    return (w or 100.0), (h or 100.0)


def render_png(svg: str, width_px: int) -> bytes:
    """PNG fallback via resvg (bundled wheels on Windows, macOS, Linux)."""
    try:
        import resvg_py
    except ImportError:  # pragma: no cover - dependency is declared
        # 1×1 transparent PNG: Word still uses the SVG; old readers show nothing.
        return bytes.fromhex(
            "89504e470d0a1a0a0000000d4948445200000001000000010806000000"
            "1f15c4890000000d49444154789c6360000002000154a24f5d0000000049454e44ae426082"
        )
    return bytes(resvg_py.svg_to_bytes(svg_string=svg, width=max(16, int(width_px))))


