"""Vector art in Word: native SVG, generated ornaments, page frames and borders.

Word 2016+ (Microsoft 365) draws SVG natively and keeps it sharp at any zoom
and in print. Each SVG is stored with a PNG fallback (rendered by resvg) for
older Word, LibreOffice and previews.

Ornaments are generated by ``islamic_art`` with traditional constructions
(woven girih, Hankin's method, parallel offsets, Bézier fleurons):

- ``star8``    — eight-point star frame with parallel outlines (optional
  number in the centre, e.g. narration numbers).
- ``rosette``  — woven strapwork rosette, 8/10/12/16-fold.
- ``shamsa``   — title-page sunburst around a woven rosette.
- ``ring``     — segmented girih ring (the Markaz Athari construction).
- ``divider``  — calligraphic swash: tapered rules into a lily-and-curls
  fleuron.
- ``divider-dots`` — light rule with a small khatam.
- ``corner``   — double rule turning round a woven rosette, with fleurons.
- ``band``     — woven border: interlocking rings with stars (default),
  octagon chain, hexagon chain, khatam chain, or a girih field.
- ``frame``    — whole-page woven border with corner rosettes.
- ``cartouche-lobed`` / ``-banner`` / ``-arch`` — label and title frames.

``add_page_frame`` anchors a frame behind the text in the header, so it
repeats on every page of the section without touching the body text.
"""

